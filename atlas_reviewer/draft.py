"""Render the review draft as Markdown. Pure.

The draft is the only output of a review. It is written for the operator
to read; nothing in it is posted anywhere.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from datetime import datetime

from atlas_reviewer.classify import tally
from atlas_reviewer.committed_secrets import CommittedSecret
from atlas_reviewer.diffs import FileDiff
from atlas_reviewer.domain import (
    Evidence,
    Matched,
    Missing,
    Omission,
    Outcome,
    PrEvent,
    Stale,
    evidence_key,
    outcome,
)
from atlas_reviewer.groups import CheckGroup, Link, group_checks
from atlas_reviewer.lenses import LensStatus, LensUse
from atlas_reviewer.notes import UNTRUSTED_QUOTING
from atlas_reviewer.ports import Narrative
from atlas_reviewer.providers import OfflineProvider
from atlas_reviewer.telemetry import SUMMARY_HEADERS, Event, summary_rows

CONTROLLER_NOTES_INTRO = (
    "Generated by code from facts the controller established, not by the model. "
    "Where the review narrative disagrees with this section, this section is authoritative. "
    + UNTRUSTED_QUOTING
)

DRAFT_BANNER = "> **Draft only -- not posted.** Produced by `atlas_reviewer` for an operator to read. Nothing was sent to GitHub."


@dataclass(frozen=True)
class NarrativeFailure:
    harness: str
    reason: str


@dataclass(frozen=True)
class PartNarrative:
    """The review of one diff part: one model call (retries included)."""

    index: int
    total: int
    files: tuple[FileDiff, ...]
    result: Narrative | NarrativeFailure

    @property
    def reviewed(self) -> bool:
        return isinstance(self.result, Narrative)

    @property
    def simulated(self) -> bool:
        """The offline provider answered: a prompt was built, no model ran."""
        return (
            isinstance(self.result, Narrative)
            and self.result.provider == OfflineProvider.name
        )

    @property
    def model_reviewed(self) -> bool:
        return self.reviewed and not self.simulated


@dataclass(frozen=True)
class DraftInput:
    event: PrEvent
    mode: str
    title: str
    evidence: tuple[Evidence, ...]
    links: tuple[Link, ...]
    controller_notes: tuple[str, ...]
    lenses: tuple[LensUse, ...]
    narratives: tuple[PartNarrative, ...]
    omissions: tuple[Omission, ...]
    model_usage: tuple[str, ...]
    redactions: int
    generated_at: datetime
    telemetry: tuple[Event, ...] = ()
    secrets: tuple[CommittedSecret, ...] | None = None


def _cell(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\r", " ")
        .replace("\n", " ")
        .strip()
        or "-"
    )


def _sort_key(e: Evidence) -> tuple[str, str]:
    key = evidence_key(e)
    return key.kind.value, key.name


def render_draft(d: DraftInput) -> str:
    sections = (
        _header(d),
        _summary(d),
        controller_notes_section(d.controller_notes),
        _secrets(d.secrets),
        _lenses(d.lenses, any(p.model_reviewed for p in d.narratives)),
        _checks(d.evidence, d.links),
        _at_head(d.evidence),
        _unknowns(d.evidence),
        _omissions(d.omissions),
        _usage(d.model_usage),
        telemetry_section(d.telemetry),
        _narratives(d.narratives),
        (
            f"---\n\n{d.redactions} secret-like string(s) were redacted from CI, runner, "
            "PR and issue text before any model call. The diff is not redacted; it is "
            "scanned for possible committed secrets instead."
        ),
    )
    return "\n\n".join(s for s in sections if s) + "\n"


def _header(d: DraftInput) -> str:
    rows = (
        ("Repository", d.event.repo),
        ("Pull request", f"#{d.event.pr_number} -- {d.title}"),
        ("Reviewed head SHA", f"`{d.event.head_sha}`"),
        ("Mode", d.mode),
        ("Generated at", d.generated_at.isoformat(timespec="seconds")),
    )
    table = "\n".join(f"| {k} | {_cell(v)} |" for k, v in rows)
    return f"# Code Quality Atlas review -- DRAFT\n\n{DRAFT_BANNER}\n\n| Field | Value |\n| --- | --- |\n{table}"


def _summary(d: DraftInput) -> str:
    t = tally(d.evidence, d.links)
    return (
        "## Evidence summary\n\n"
        "Counts are independent checks at the reviewed head SHA: a check run, its job, "
        "its log and the workflow run holding it are one check, not four.\n\n"
        f"- Pass: {t.passed}\n- Fail: {t.failed}\n"
        f"- UNKNOWN at the head SHA (missing or inconclusive): {t.unknown}\n"
        f"- Not read (logs, artifacts, archive entries or GitHub lists; UNKNOWN): {t.unread}\n"
        f"- Stale (other commits; UNKNOWN for this SHA): {t.stale}\n"
        f"- Present, no verdict (artifacts): {t.present}\n"
        f"- Supporting evidence folded into the checks above (jobs, logs, workflow runs): {t.supporting}\n\n"
        "UNKNOWN is never counted as passing."
    )


def controller_notes_section(lines: Iterable[str]) -> str:
    bullets = "\n".join(f"- {line}" for line in lines)
    return f"## Controller notes\n\n{CONTROLLER_NOTES_INTRO}\n\n{bullets}"


def _lenses(uses: tuple[LensUse, ...], ran: bool) -> str:
    if not uses:
        return "## Review lenses\n\nNone selected."
    which = (
        "A lens ran only if its whole body was in the prompt; a NOT RUN lens's "
        "area was not reviewed."
        if ran
        else "No model call returned a review, so no lens ran: every lens is NOT "
        "RUN, and the table lists what was planned for the prompt."
    )
    rows = "\n".join(
        "| "
        + " | ".join(
            _cell(c)
            for c in (
                u.name,
                u.status.value if ran else LensStatus.NOT_RUN.value,
                str(u.chars),
                u.why,
                u.reason or ("" if ran else "no model call returned a review"),
            )
        )
        + " |"
        for u in uses
    )
    return (
        "## Review lenses\n\n"
        "Lenses are chosen by the `choosing-review-lenses` picker (or the critical tier "
        "when it does not run), critical tier first; each body is read from the skill "
        "bundle and placed in the model prompt whole, or not at all. "
        f"{which}\n\n"
        "| Lens | Status | Characters | Chosen as | Why not run |\n"
        "| --- | --- | --- | --- | --- |\n" + rows
    )


def _checks(evidence: Iterable[Evidence], links: tuple[Link, ...]) -> str:
    groups = group_checks(evidence, links)
    if not groups:
        return ""
    rows = "\n".join(_group_row(g) for g in sorted(groups, key=_group_sort_key))
    return (
        "## Independent checks at the reviewed head SHA\n\n"
        "Supporting evidence is listed with the check it belongs to and is not counted again.\n\n"
        "| Outcome | Kind | Name | Supporting evidence |\n| --- | --- | --- | --- |\n"
        + rows
    )


def _group_sort_key(g: CheckGroup) -> tuple[str, str]:
    return _sort_key(g.root)


def _group_row(g: CheckGroup) -> str:
    key = g.root.item.provenance.key
    label = g.outcome.value if g.outcome is Outcome.INFO else g.outcome.value.upper()
    supporting = ", ".join(
        f"{m.item.provenance.key.kind.value} {m.item.provenance.source_id}"
        for m in (*g.supporting, *g.context)
    )
    cells = (label, key.kind.value, key.name, supporting or "none")
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _at_head(evidence: Iterable[Evidence]) -> str:
    matched = sorted((e for e in evidence if isinstance(e, Matched)), key=_sort_key)
    if not matched:
        return "## Evidence at the reviewed head SHA\n\nNone."
    rows = "\n".join(_matched_row(m) for m in matched)
    return (
        "## Evidence at the reviewed head SHA\n\n"
        "| Outcome | Kind | Name | Tool @ version | Provenance | Fetched at |\n"
        "| --- | --- | --- | --- | --- | --- |\n" + rows
    )


def _matched_row(m: Matched) -> str:
    i = m.item
    cells = (
        _outcome_label(m),
        i.provenance.key.kind.value,
        i.provenance.key.name,
        f"{i.tool.name} @ {i.tool.version}",
        i.provenance.source_id,
        i.fetched_at.isoformat(timespec="seconds"),
    )
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _outcome_label(m: Matched) -> str:
    result = outcome(m)
    if result is Outcome.UNKNOWN:
        return f"UNKNOWN ({m.item.conclusion.value})"
    return result.value.upper() if result is not Outcome.INFO else result.value


def _unknowns(evidence: Iterable[Evidence]) -> str:
    rows = [
        _unknown_row(e)
        for e in sorted(evidence, key=_sort_key)
        if outcome(e) is Outcome.UNKNOWN
    ]
    if not rows:
        return "## UNKNOWN -- not counted as passing\n\nNone."
    return (
        "## UNKNOWN -- not counted as passing\n\n"
        "| Status | Kind | Name | Why |\n| --- | --- | --- | --- |\n" + "\n".join(rows)
    )


def _unknown_row(e: Evidence) -> str:
    key = evidence_key(e)
    status, why = _unknown_reason(e)
    return (
        "| "
        + " | ".join(_cell(c) for c in (status, key.kind.value, key.name, why))
        + " |"
    )


def _unknown_reason(e: Evidence) -> tuple[str, str]:
    match e:
        case Stale(item=item):
            return (
                "stale",
                f"evidence is for `{item.head_sha[:12]}` ({item.provenance.source_id})",
            )
        case Missing(reason=reason):
            return "missing", reason
        case Matched(item=item):
            return (
                "inconclusive",
                f"conclusion `{item.conclusion.value}` at the head SHA",
            )
    raise TypeError(f"not evidence: {e!r}")  # pragma: no cover


def _secrets(found: tuple[CommittedSecret, ...] | None) -> str:
    """Controller findings, not model output. `None` means the diff was not
    fetched, so there was nothing to scan."""
    if found is None:
        return ""
    head = (
        "## Possible committed secrets\n\n"
        "Found by the controller's pattern scan of the diff, not by the model. "
        "Values are never shown. A committed secret is already exposed in the "
        "repository's history: if one is real, rotate it, then remove it."
    )
    if not found:
        return f"{head}\n\nNone found."
    rows = "\n".join(
        "| "
        + " | ".join(
            _cell(c)
            for c in (
                "HIGH",
                s.path,
                "-" if s.line is None else f"{s.line} ({s.side})",
                s.label,
                f"possible committed secret in {s.path}; rotate if real",
            )
        )
        + " |"
        for s in found
    )
    return (
        f"{head}\n\n| Severity | File | Line | Pattern | Finding |\n"
        "| --- | --- | --- | --- | --- |\n" + rows
    )


def _omissions(omissions: tuple[Omission, ...]) -> str:
    if not omissions:
        return "## Omissions and limits hit\n\nNone."
    rows = "\n".join(
        "| " + " | ".join(_cell(c) for c in (o.source, o.limit, o.detail)) + " |"
        for o in omissions
    )
    return (
        "## Omissions and limits hit\n\n"
        "Not read in full; nothing here is counted as passing.\n\n"
        "| Source | Limit | Detail |\n| --- | --- | --- |\n" + rows
    )


def _usage(lines: tuple[str, ...]) -> str:
    return "## Model usage\n\n" + "\n".join(f"- {_cell(line)}" for line in lines)


def render_evidence(
    evidence: tuple[Evidence, ...],
    omissions: tuple[Omission, ...] = (),
    links: tuple[Link, ...] = (),
) -> str:
    """The grouped checks, evidence tables, omissions, and each head-SHA
    item's (redacted) detail text."""
    details = "\n\n".join(
        f"### {m.item.provenance.source_id}\n{m.item.detail.text}"
        for m in sorted((e for e in evidence if isinstance(e, Matched)), key=_sort_key)
        if m.item.detail.text
    )
    return (
        f"{_checks(evidence, links)}\n\n"
        f"{_at_head(evidence)}\n\n{_unknowns(evidence)}\n\n{_omissions(omissions)}"
        f"\n\n## Details\n\n{details or 'None.'}"
    )


def telemetry_section(events: tuple[Event, ...]) -> str:
    if not events:
        return ""
    header = "| " + " | ".join(SUMMARY_HEADERS) + " |"
    rule = "| " + " | ".join("---" for _ in SUMMARY_HEADERS) + " |"
    rows = "\n".join(
        "| " + " | ".join(_cell(c) for c in row) + " |" for row in summary_rows(events)
    )
    return (
        "## Lifecycle telemetry\n\n"
        "One row per step, timed by the controller in seconds from the start of the run. "
        "Errors carry their phase and step. The CLI writes the same events as JSONL.\n\n"
        f"{header}\n{rule}\n{rows}"
    )


NO_NARRATIVE = (
    "No model call was made, so there is no narrative and nothing in the diff "
    "was reviewed. The controller notes say why."
)


def _narratives(parts: tuple[PartNarrative, ...]) -> str:
    body = "\n\n".join(_part(p) for p in parts) or NO_NARRATIVE
    return f"## Review narrative\n\n{body}"


def _part(p: PartNarrative) -> str:
    heading = (
        f"### Diff part {p.index} of {p.total} ({len(p.files)} file(s))\n\n"
        if p.total > 1
        else ""
    )
    return heading + _narrative(p.result)


def _narrative(n: Narrative | NarrativeFailure) -> str:
    if isinstance(n, NarrativeFailure):
        return f"Harness `{n.harness}` produced no narrative: {_cell(n.reason)}"
    quoted = "\n".join(
        f"> {line}" if line else ">" for line in n.text.text.splitlines()
    )
    return (
        f"Harness `{n.harness}`, provider `{n.provider}`. Model output is unverified; "
        "check every claim against the evidence above.\n\n" + quoted
    )
